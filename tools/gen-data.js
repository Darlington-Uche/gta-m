// Builds js/data.js from tools/specs.json (deterministic)
const fs = require('fs'), path = require('path');
const specs = require('./specs.json');
let s = 12345; const r = () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296; };
const artists = [
  ['MiamiArt', 'MA'], ['GTACollector', 'GC'], ['OGArtist', 'OG'], ['LibertyCreator', 'LC'], ['LosSantosArt', 'LS'],
  ['WestCoastVisuals', 'WV'], ['IllArchive', 'IA'], ['RetroGTA', 'RG'], ['PixelForger', 'PF'], ['NextGenArt', 'NG'],
  ['NeonDrifter', 'ND'], ['SunsetSyndicate', 'SS']
];
const eraNames = { g1: 'GTA 1 (1997)', g2: 'GTA 2 (1999)', g3: 'GTA III (2001)', vice: 'Vice City (2002)', sa: 'San Andreas (2004)', iv: 'GTA IV (2008)', v: 'GTA V (2013)', vi: 'GTA VI (2025)' };
const eraShort = { g1: 'GTA 1', g2: 'GTA 2', g3: 'GTA III', vice: 'Vice City', sa: 'San Andreas', iv: 'GTA IV', v: 'GTA V', vi: 'GTA VI' };
const rarities = ['Common', 'Rare', 'Epic', 'Legendary'];
const desc = {
  Locations: 'A moody, stylised take on a place that lives in every fan\'s memory. Painted in vector with a heavy neon palette.',
  Vehicles: 'Chrome, neon and a long road ahead. An original vehicle study built for collectors who love the open road.',
  Characters: 'Original character study inspired by the swagger of the series. Flat colour, bold silhouettes, loud attitude.',
  Artwork: 'A wide scene piece blending skyline, haze and light. Made as a poster-style tribute to the GTA era it belongs to.'
};
const art = specs.map((sp, i) => {
  const a = artists[Math.floor(r() * artists.length)];
  const rarity = r() > 0.9 ? 'Legendary' : r() > 0.72 ? 'Epic' : r() > 0.4 ? 'Rare' : 'Common';
  const base = { Common: 2, Rare: 5, Epic: 11, Legendary: 22 }[rarity];
  const price = Math.round((base + r() * base * 0.9) * 10) / 10;
  const fixed = r() > 0.8;
  return {
    id: sp.n, title: sp.t, era: sp.era, eraLabel: eraNames[sp.era], eraShort: eraShort[sp.era], category: sp.cat,
    img: 'assets/art/art-' + String(sp.n).padStart(2, '0') + '.svg',
    artist: a[0], artistInit: a[1], price, fixed, rarity,
    likes: Math.floor(60 + r() * 460), bids: fixed ? 0 : Math.floor(2 + r() * 28),
    endsIn: fixed ? 0 : Math.floor(600 + r() * 60 * 3600), // seconds from page load
    listedAgo: Math.floor(r() * 72), // hours
    description: desc[sp.cat],
    tags: [eraShort[sp.era].toLowerCase(), sp.cat.toLowerCase(), rarity.toLowerCase()],
    tokenShare: [50, 60, 70, 80][Math.floor(r() * 4)]
  };
});
const colDefs = [
  ['vi', 'GTA VI – Vice City Reborn', 'Next generation. A new era of chaos.'],
  ['vice', 'Vice City Classics', 'Neon lights. Big dreams. Timeless art.'],
  ['sa', 'San Andreas Legends', 'Representing the streets of San Andreas.'],
  ['v', 'GTA V Icons', 'The characters, vehicles and moments that defined a generation.'],
  ['iv', 'GTA IV – Liberty City', 'A darker, grittier side of the American dream.'],
  ['g3', 'GTA 3 – The Beginning', 'Where a new era of open world started.'],
  ['g2', 'GTA 2 – Retro Chaos', 'A classic era of crime and mayhem.'],
  ['g1', 'GTA 1 – The Origin', 'The game that started it all.']
];
const collections = colDefs.map((c, i) => {
  const items = art.filter(a => a.era === c[0]);
  const floor = Math.min(...items.map(a => a.price));
  return { id: c[0], name: c[1], blurb: c[2], era: c[0], count: items.length * (28 + Math.floor(r() * 40)) / 1 | 0, floor: Math.round(floor * 10) / 10, cover: items[0].img, covers: items.slice(0, 4).map(a => a.img), items: items.map(a => a.id), volume: Math.round((50 + r() * 900) * 10) / 10, owners: Math.floor(40 + r() * 400) };
});
const out = `/* Auto-generated by tools/gen-data.js — mock catalog, replace with API later */\nwindow.GTA_DATA = ${JSON.stringify({ art, collections, eras: eraNames, eraShort }, null, 1)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'data.js'), out);
console.log('data.js', art.length, 'art', collections.length, 'collections');
